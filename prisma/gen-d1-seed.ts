/// <reference types="bun-types" />
/**
 * Generates prisma/d1-seed.sql from the local SQLite database (db/custom.db).
 *
 * The output is idempotent:
 *  - Project/Article rows upsert on slug (content fields refresh, engagement
 *    metrics like views/likes are preserved for existing rows)
 *  - the visit counter is inserted only if absent (production keeps its own)
 *
 * Run:  bun prisma/gen-d1-seed.ts
 */
import { Database } from "bun:sqlite";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const dbPath = join(import.meta.dir, "..", "db", "custom.db");
const outPath = join(import.meta.dir, "d1-seed.sql");

const sqlite = new Database(dbPath, { readonly: true });

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "1" : "0";
  if (v instanceof Date) return `'${v.toISOString()}'`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

type Row = Record<string, unknown>;

const all = (sql: string): Row[] => sqlite.prepare(sql).all() as Row[];

const projectRows = all(`SELECT * FROM Project ORDER BY "order" ASC`);
const articleRows = all(`SELECT * FROM Article ORDER BY publishedAt ASC`);
const statRows = all(`SELECT * FROM SiteStat`);

const lines: string[] = [
  "-- Generated by prisma/gen-d1-seed.ts — edit the generator, not this file.",
  "-- Idempotent content seed for Cloudflare D1 (run AFTER d1-schema.sql).",
  "",
];

for (const r of projectRows) {
  lines.push(
    `INSERT INTO "Project" ("id", "slug", "title", "titleEn", "repo", "demoUrl", "description", "descriptionEn", "category", "tags", "icon", "featured", "views", "order", "createdAt")\n` +
      `VALUES (${q(r.id)}, ${q(r.slug)}, ${q(r.title)}, ${q(r.titleEn)}, ${q(r.repo)}, ${q(r.demoUrl)}, ${q(r.description)}, ${q(r.descriptionEn)}, ${q(r.category)}, ${q(r.tags)}, ${q(r.icon)}, ${r.featured ? 1 : 0}, ${Number(r.views ?? 0)}, ${Number(r.order ?? 0)}, ${q(r.createdAt)})\n` +
      `ON CONFLICT("slug") DO UPDATE SET\n` +
      `  "title" = excluded."title", "titleEn" = excluded."titleEn", "repo" = excluded."repo",\n` +
      `  "demoUrl" = excluded."demoUrl",\n` +
      `  "description" = excluded."description", "descriptionEn" = excluded."descriptionEn",\n` +
      `  "category" = excluded."category", "tags" = excluded."tags", "icon" = excluded."icon",\n` +
      `  "featured" = excluded."featured", "order" = excluded."order";`
  );
}

for (const r of articleRows) {
  lines.push(
    `INSERT INTO "Article" ("id", "slug", "title", "titleEn", "excerpt", "excerptEn", "content", "category", "icon", "readTime", "views", "likes", "publishedAt")\n` +
      `VALUES (${q(r.id)}, ${q(r.slug)}, ${q(r.title)}, ${q(r.titleEn)}, ${q(r.excerpt)}, ${q(r.excerptEn)}, ${q(r.content)}, ${q(r.category)}, ${q(r.icon)}, ${Number(r.readTime ?? 5)}, ${Number(r.views ?? 0)}, ${Number(r.likes ?? 0)}, ${q(r.publishedAt)})\n` +
      `ON CONFLICT("slug") DO UPDATE SET\n` +
      `  "title" = excluded."title", "titleEn" = excluded."titleEn", "excerpt" = excluded."excerpt",\n` +
      `  "excerptEn" = excluded."excerptEn", "content" = excluded."content", "category" = excluded."category",\n` +
      `  "icon" = excluded."icon", "readTime" = excluded."readTime";`
  );
}

for (const r of statRows) {
  lines.push(
    `INSERT INTO "SiteStat" ("key", "value", "updatedAt") VALUES (${q(r.key)}, ${Number(r.value ?? 0)}, ${q(r.updatedAt)})\n` +
      `ON CONFLICT("key") DO NOTHING;`
  );
}

lines.push("");
writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(
  `d1-seed.sql written: ${projectRows.length} projects, ${articleRows.length} articles, ${statRows.length} stats`
);
sqlite.close();
