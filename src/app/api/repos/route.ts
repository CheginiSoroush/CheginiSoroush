function metaFor(name: string) {
  return REPO_META[name.toLowerCase()] ?? {};
}

function mapRepo(r: {
  name: string;
  html_url: string;
  description: string | null;
  language: string | null;
  stargazers_count: number;
  forks_count: number;
  fork: boolean;
  private?: boolean;
  archived: boolean;
  topics?: string[];
  homepage: string | null;
  pushed_at: string;
  updated_at: string;
}): GitHubRepo {
  const meta = metaFor(r.name);
  return {
    name: r.name,
    url: r.html_url,
    description: r.description ?? meta.en ?? null,
    descriptionFa: meta.fa ?? null,
    language: r.language,
    stars: r.stargazers_count ?? 0,
    forks: r.forks_count ?? 0,
    isFork: Boolean(r.fork),
    isPrivate: Boolean(r.private),
    archived: Boolean(r.archived),
    topics: Array.isArray(r.topics) ? r.topics.slice(0, 6) : [],
    homepage: r.homepage || null,
    pushedAt: r.pushed_at,
    updatedAt: r.updated_at,
  };
}

async function fetchFromGitHub(): Promise<GitHubRepo[] | null> {
  try {
    const token = process.env.GITHUB_TOKEN;
    const headers: Record<string, string> = {
      Accept: "application/vnd.github+json",
      "User-Agent": "imsoroush-portfolio",
    };
    if (token) {
      headers.Authorization = `Bearer ${token}`;
    }
    // Authenticated call lists owned repos including private ones.
    const endpoint = token
      ? "https://api.github.com/user/repos?visibility=all&affiliation=owner&sort=pushed&per_page=100"
      : `https://api.github.com/users/${GITHUB_USER}/repos?per_page=100&sort=pushed&type=owner`;
    const res = await fetch(endpoint, { headers, cache: "no-store" });
    if (!res.ok) {
      console.error("/api/repos GitHub failed:", res.status);
      return null;
    }
    const list = (await res.json()) as Parameters<typeof mapRepo>[0][];
    if (!Array.isArray(list)) return null;
    return list.map(mapRepo);
  } catch (error) {
    console.error("/api/repos fetch error:", error);
    return null;
  }
}

async function readDbSnapshot(): Promise<ReposPayload | null> {
  try {
    const row = await store.getSnapshot("RepoSnapshot");
    if (!row) return null;
    const repos = JSON.parse(row.payloadJson) as GitHubRepo[];
    if (!Array.isArray(repos) || repos.length === 0) return null;
    return {
      repos,
      source: "db",
      includesPrivate: repos.some((r) => r.isPrivate),
      fetchedAt: new Date(row.updatedAt).getTime(),
    };
  } catch {
    return null;
  }
}

async function writeDbSnapshot(repos: GitHubRepo[]): Promise<void> {
  try {
    await store.putSnapshot("RepoSnapshot", JSON.stringify(repos));
  } catch (error) {
    console.error("/api/repos snapshot write failed:", error);
  }
}

